grep -Fq 'if frame >= END_FRAME or S.t > 7 then proceed() end' "$APP/ui/screens/boot.lua"
! grep -Fq 'if lg == "SELECT" then' "$APP/ui/init.lua"
! grep -Fq 'in_stream and "library" or "stream_library"' "$APP/ui/init.lua"
! grep -Fq 'elseif b == "SELECT" then' "$APP/ui/screens/library.lua"
grep -Fq 'elseif b == "SELECT" then' "$APP/ui/screens/home.lua"
! grep -Fq 'auto_discover_rom_paths()' "$APP/core/library.lua"
! grep -Fq 'Auto-detect ROM roots' "$APP/ui/screens/folders.lua"
grep -Fq 'ADD GAMECUBE ROM FOLDER' "$APP/ui/screens/folders.lua"
grep -Fq 'ADD WII ROM FOLDER' "$APP/ui/screens/folders.lua"
grep -Fq 'FolderWaker' "$APP/ui/screens/settings.lua"
grep -Fq 'FIX CONTENT EXPLORER FOLDERS?' "$APP/ui/screens/folders.lua"
! grep -Fq 'Registratore Z' "$APP/ui/screens/settings.lua"
! grep -Fq 'GameSettings database' "$APP/ui/screens/settings.lua"
! grep -Fq 'Controller hotkeys' "$APP/ui/screens/settings.lua"
! grep -Fq 'label = "Safe Exit"' "$APP/ui/screens/settings.lua"
! grep -Fq 'gamesettings_json' "$APP/core/boot_initializer.lua"
! grep -Fq 'gamesettings_deployer' "$APP/core/boot_initializer.lua"
grep -Fq 'muOS Content Explorer explicitly blocks' "$APP/ui/screens/folders.lua"
grep -Fq 'scan_depth        = 8' "$APP/core/settings.lua"
grep -Fq 'Library.scan_step, 0.006' "$APP/core/boot_initializer.lua"
! grep -Fq 'Library.scan()' "$APP/core/boot_initializer.lua"
grep -Fq 'n_db_cfg' "$APP/ui/screens/gameset_browser.lua"
grep -Fq 'Scan LAN + Tailscale' "$APP/ui/screens/stream_settings.lua"
grep -Fq 'read_discovered_hosts' "$APP/ui/screens/stream_settings.lua"
grep -Fq 'S.mode = "hosts"' "$APP/ui/screens/stream_settings.lua"
grep -Fq 'SELECT SUNSHINE HOST' "$APP/ui/screens/stream_settings.lua"
grep -Fq 'tailscale status --json' "$APP/tools/stream/discover.sh"
grep -Fq 'discovered_host.txt' "$APP/tools/stream/discover.sh"
grep -Fq 'local function interface_is_up' "$APP/ui/statusbar.lua"
grep -Fq '/operstate' "$APP/ui/statusbar.lua"
grep -Fq 'M._wifi.up = interface_is_up(iface)' "$APP/ui/statusbar.lua"
grep -Fq 'function M.invalidate()' "$APP/core/gameset_loader.lua"
grep -Fq 'S.preview = { row = row, lines = lines, scroll = 0 }' "$APP/ui/screens/gameset_browser.lua"
grep -Fq 'p.lines[p.scroll + i]' "$APP/ui/screens/gameset_browser.lua"
# Every shipped controller profile must follow the SDL Button n map.
for f in "$APP"/workshop/controller/GameCube/*/GCPadNew.ini; do
    [ -f "$f" ] || continue
    grep -Fq 'Buttons/A = `Button 1`' "$f"
    grep -Fq 'Buttons/B = `Button 0`' "$f"
    grep -Fq 'Buttons/Start = `Button 7`' "$f"
    grep -Fq 'Buttons/Z = `Button 11`' "$f"
    grep -Fq 'Triggers/L = `Button 4`' "$f"
    grep -Fq 'Triggers/L-Analog = `Button 9`' "$f"
    grep -Fq 'Triggers/R = `Button 5`' "$f"
    grep -Fq 'Triggers/R-Analog = `Button 12`' "$f"
done
for f in "$APP"/workshop/controller/Wii/*/WiimoteNew.ini; do
    [ -f "$f" ] || continue
    grep -Fq 'Buttons/A = `Button 1`' "$f"
    grep -Fq 'Buttons/B = `Button 0`' "$f"
    grep -Fq 'Buttons/1 = `Button 2`' "$f"
    grep -Fq 'Buttons/2 = `Button 3`' "$f"
    grep -Fq 'Buttons/+ = `Button 7`' "$f"
    grep -Fq 'Buttons/- = `Button 6`' "$f"
    grep -Fq 'Buttons/Home = `Button 8`' "$f"
done
sh -n "$APP/tools/stream/discover.sh"
bash -n "$APP/scripts/launch.sh"
echo "RtUI / RtStream feature contract: OK"
